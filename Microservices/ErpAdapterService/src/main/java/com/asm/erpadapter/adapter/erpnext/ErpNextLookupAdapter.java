    private static final DateTimeFormatter T = DateTimeFormatter.ofPattern("HH:mm:ss");

    // ── Company scoping ──────────────────────────────────────────────────────────

    /**
     * Resolve the single company whose data we read. Fail-loud on ambiguity — never guess.
     * @throws ErpAdapterException if the instance has &gt;1 company and none is configured.
     */
    private String resolveCompany() {
        String configured = erp.companyScope();
        if (!configured.isBlank()) return configured;
        List<Map<String, Object>> companies = erp.getList("Company", List.of("name"), null, 0, "creation asc");
        if (companies.isEmpty()) return null;
        if (companies.size() == 1) return asString(companies.get(0).get("name"));
        List<String> names = companies.stream().map(c -> asString(c.get("name"))).toList();
        throw new ErpAdapterException(
                "ERPNext instance hosts multiple companies " + names + " — set 'company' in ERP settings "
                        + "to pick which one ASM should read (1 instance = 1 company).", 400);
    }

    private List<Object> companyFilter(String company) {
        return List.of("company", "=", company);
    }

    // ── Search Clients (manual create flow) ──────────────────────────────────────

    @Override
    public List<ErpClientDTO> searchClients(String search, int limit) {
        long start = System.currentTimeMillis();
        String term = search != null ? search.trim() : "";
        List<List<Object>> filters = new ArrayList<>();
        filters.add(List.of("disabled", "=", 0));
        if (!term.isEmpty()) filters.add(List.of("customer_name", "like", "%" + term + "%"));

        List<Map<String, Object>> rows = erp.getList("Customer",
                List.of("name", "customer_name", "mobile_no", "email_id"), filters, limit, "customer_name asc");

        List<ErpClientDTO> result = new ArrayList<>();
        for (Map<String, Object> r : rows) {
            String id = asString(r.get("name"));
            if (id == null) continue;
            // Customer carries no phone/email inline in most installs — they live on a linked Contact.
            // Best-effort from mobile_no/email_id when present; null otherwise (documented limitation).
            result.add(ErpClientDTO.builder()
                    .erpClientId(id)
                    .name(orEmpty(asString(r.get("customer_name"))))
                    .phone(asString(r.get("mobile_no")))
                    .email(asString(r.get("email_id")))
                    .build());
        }
        log.info("[erpnext] searchClients term='{}' count={} durationMs={}", term, result.size(), System.currentTimeMillis() - start);
        return result;
    }

    // ── Search Products (manual create flow) ─────────────────────────────────────

    @Override
    public List<ErpProductDTO> searchProducts(String search, int limit) {
        long start = System.currentTimeMillis();
        String term = search != null ? search.trim() : "";
        List<List<Object>> filters = new ArrayList<>();
        filters.add(List.of("disabled", "=", 0));
        filters.add(List.of("is_sales_item", "=", 1));
        if (!term.isEmpty()) filters.add(List.of("item_name", "like", "%" + term + "%"));

        List<Map<String, Object>> rows = erp.getList("Item",
                List.of("item_code", "item_name", "stock_uom", "standard_rate", "valuation_rate",
                        "weight_per_unit", "description", "is_sales_item"),
                filters, limit, "item_name asc");

        List<ErpProductDTO> result = new ArrayList<>();
        for (Map<String, Object> r : rows) {
            String sku = asString(r.get("item_code"));
            if (sku == null) continue;
            // Selling price lives in the Item Price doctype (price lists); fall back to standard/valuation
            // rate as an indicative price without a second per-item fetch.
            BigDecimal price = asBigDecimal(r.get("standard_rate"));
            if (price == null || price.signum() == 0) price = asBigDecimal(r.get("valuation_rate"));
            Double weight = asDouble(r.get("weight_per_unit"));
            result.add(ErpProductDTO.builder()
                    .erpProductId(sku)
                    .name(orEmpty(asString(r.get("item_name"))))
                    .sku(sku)
                    .price(price != null ? price.doubleValue() : 0.0)
                    .weightKg(weight != null ? weight : 0.0)
                    .available(asBool(r.get("is_sales_item")))
                    .description(asString(r.get("description")))
                    .build());
        }
        log.info("[erpnext] searchProducts term='{}' count={} durationMs={}", term, result.size(), System.currentTimeMillis() - start);
        return result;
    }

    // ── Pending orders = Sales Orders still to deliver ───────────────────────────

    /** Sales Order statuses that mean "confirmed, still awaiting delivery". */
    private static final List<Object> TO_DELIVER_STATUSES = List.of("To Deliver", "To Deliver and Bill");

    @Override
    public List<ErpPendingOrderSummaryDTO> getPendingOrders(int limit) {
        long start = System.currentTimeMillis();
        String company = resolveCompany();
        if (company == null) return List.of();

        List<List<Object>> filters = List.of(
                List.of("docstatus", "=", 1),          // confirmed sale order
                companyFilter(company),
                List.of("status", "in", TO_DELIVER_STATUSES));

        List<String> soFields = List.of("name", "customer", "customer_name", "contact_mobile", "transaction_date",
                "delivery_date", "grand_total", "currency", "set_warehouse", "total_qty", "per_delivered",
                "po_no", "payment_terms_template", "shipping_address_name", "customer_address");
        List<Map<String, Object>> rows = listWidened("Sales Order", soFields, filters, limit, "delivery_date asc");

        // Batch-resolve delivery addresses in ONE call (mirrors the Odoo adapter's partner batch), so the
        // list shows the destination without an N+1 per-order Address fetch.
        Map<String, Map<String, Object>> addrByName = batchAddresses(rows);
        Map<String, Map<String, Object>> customerByName = batchCustomers(rows);

        List<ErpPendingOrderSummaryDTO> result = new ArrayList<>();
        for (Map<String, Object> r : rows) {
            String so = asString(r.get("name"));
            if (so == null) continue;
            final String wh = asString(r.get("set_warehouse"));
            final Map<String, Object> addr = addrByName.get(
                    firstNonBlank(asString(r.get("shipping_address_name")), asString(r.get("customer_address"))));
            // Mapped here as well as in the preview: wiring only one of the two would show different
            // values for the same order depending on which screen you were looking at.
            Map<String, Map<String, Object>> records =
                    headerRecords(r, customerByName.get(asString(r.get("customer"))), addr);
            // A partially-delivered SO (per_delivered > 0) re-appearing here IS the reliquat/backorder.
            Double perDelivered = asDouble(r.get("per_delivered"));
            boolean isBackorder = perDelivered != null && perDelivered > 0;
            result.add(ErpPendingOrderSummaryDTO.builder()
                    .erpOrderId(mappedString(ERP_ORDER_ID, records, () -> so))
                    .saleOrderRef(mappedString(SALE_ORDER_REF, records, () -> so))
                    .customerRef(mappedString(CUSTOMER_REF, records, () -> asString(r.get("po_no"))))
                    .customerName(mappedString(CUSTOMER_NAME, records, () -> asString(r.get("customer_name"))))
                    .customerPhone(mappedString(CUSTOMER_PHONE, records, () -> asString(r.get("contact_mobile"))))
                    .deliveryAddress(mappedString(DELIVERY_ADDRESS, records,
                            () -> addr != null ? buildAddress(addr) : null))
                    .deliveryCity(mappedString(DELIVERY_CITY, records,
                            () -> addr != null ? asString(addr.get("city")) : null))
                    .deliveryPostalCode(mappedString(DELIVERY_POSTAL_CODE, records,
                            () -> addr != null ? asString(addr.get("pincode")) : null))
                    .totalAmount(mappedDecimal(TOTAL_AMOUNT, records, () -> asBigDecimal(r.get("grand_total"))))
                    .currency(mappedString(CURRENCY, records, () -> asString(r.get("currency"))))
                    // Default false: see CanonicalField.COD_REQUIRED.
                    .codRequired(mappedBoolean(COD_REQUIRED, records, () -> false))
                    .codAmount(mappedDecimal(COD_AMOUNT, records, () -> asBigDecimal(r.get("grand_total"))))
                    .warehouseCode(mappedString(WAREHOUSE_CODE, records, () -> wh))
                    .warehouseName(mappedString(WAREHOUSE_NAME, records, () -> wh))
                    .ready(mappedBoolean(READY, records, () -> true))
                    .priority(mappedString(PRIORITY, records, () -> "NORMAL"))
                    .backorder(isBackorder)   // reliquat badge; no originBl — the row already shows the SO (self-reference)
                    .scheduledAt(mappedDateTime(SCHEDULED_AT, records, () -> parseDateTime(r.get("delivery_date"), null)))
                    .dateOrder(mappedDateTime(DATE_ORDER, records, () -> parseDateTime(r.get("transaction_date"), null)))
                    .build());
        }
        log.info("[erpnext] getPendingOrders (SO to-deliver) company='{}' count={} durationMs={}", company, result.size(), System.currentTimeMillis() - start);
        return result;
    }

    @Override
    public ErpPendingOrderPreviewDTO getPendingOrderPreview(String erpOrderId) {
        if (erpOrderId == null || erpOrderId.isBlank()) return null;
        Map<String, Object> so = erp.getDoc("Sales Order", erpOrderId);
        if (so == null) return null;

        List<ErpOrderItemDTO> items = new ArrayList<>();
        int totalQty = 0;
        BigDecimal totalWeight = BigDecimal.ZERO;
        String firstWarehouse = null;
        Object rawItems = so.get("items");

        // Frappe puts tax on the document, not on the line: a line has a rate, the order has a
        // grand_total, and nothing in between. The taxed unit price is therefore derived by spreading
        // the difference across the lines in proportion to their own value — exact whenever the tax is
        // itself proportional, which covers VAT.
        final BigDecimal taxFactor = taxFactorOf(so, rawItems);
        if (rawItems instanceof List<?> lines) {
            for (Object o : lines) {
                if (!(o instanceof Map<?, ?> line)) continue;
                @SuppressWarnings("unchecked")
                Map<String, Object> li = (Map<String, Object>) line;
                Integer qty = asInt(li.get("qty"));
                Integer delivered = asInt(li.get("delivered_qty"));
                int remaining = (qty != null ? qty : 0) - (delivered != null ? delivered : 0);
                if (remaining <= 0) continue;              // this line is already fully delivered
                // Line scope: a bare path is read against the order row, and the Item is fetched only
                // when the tenant mapped something onto it.
                Map<String, Map<String, Object>> lineRecords = new HashMap<>();
                lineRecords.put("Sales Order Item", li);
                lineRecords.put("Sales Order", so);
                if (!fieldMapping.extraFieldsFor("Item").isEmpty()) {
                    Map<String, Object> item = erp.getDoc("Item", asString(li.get("item_code")));
                    if (item != null) lineRecords.put("Item", item);
                }

                final int left = remaining;
                Integer mappedQty = mappedInt(ITEM_QUANTITY, lineRecords, () -> left);
                int quantity = mappedQty != null ? mappedQty : left;
                BigDecimal unitWeight = mappedDecimal(ITEM_UNIT_WEIGHT_KG, lineRecords,
                        () -> asBigDecimal(li.get("weight_per_unit")));
                items.add(ErpOrderItemDTO.builder()
                        .name(mappedString(ITEM_NAME, lineRecords, () -> asString(li.get("item_name"))))
                        .sku(mappedString(ITEM_SKU, lineRecords, () -> asString(li.get("item_code"))))
                        .quantity(quantity)                // what's left to deliver (handles partial/backorder)
                        .unitPrice(mappedDecimal(ITEM_UNIT_PRICE, lineRecords, () -> asBigDecimal(li.get("rate"))))
                        .unitPriceTtc(taxFactor == null ? null
                                : applyFactor(asBigDecimal(li.get("rate")), taxFactor))
                        .unitWeightKg(unitWeight)
                        .productType(mappedString(ITEM_PRODUCT_TYPE, lineRecords, () -> asString(li.get("item_group"))))
                        .build());
                totalQty += quantity;
                if (unitWeight != null) totalWeight = totalWeight.add(unitWeight.multiply(BigDecimal.valueOf(quantity)));
                if (firstWarehouse == null) firstWarehouse = asString(li.get("warehouse"));
            }
        }

        // Delivery address: resolve the linked Address doc and build a CLEAN address from its structured
        // fields — never the raw address_display, which is HTML (<br> lines). Order: SO shipping address,
        // then customer address, then the customer's default Address. HTML display is a last resort.
        String address = null;
        String city = null;
        String addrName = firstNonBlank(asString(so.get("shipping_address_name")), asString(so.get("customer_address")));
        if (addrName == null) addrName = defaultCustomerAddress(asString(so.get("customer")));
        Map<String, Object> addr = null;
        if (addrName != null) {
            addr = erp.getDoc("Address", addrName);
            if (addr != null) {
                city = asString(addr.get("city"));
                address = buildAddress(addr);
            }
        }
        if (address == null) address = stripHtml(asString(so.get("address_display")));

        // Kept so a mapping can name Customer: or Address: explicitly. Fetched only when the tenant
        // has actually mapped something onto the customer — an unmapped tenant pays nothing.
        Map<String, Object> customer = null;
        if (!fieldMapping.extraFieldsFor("Customer").isEmpty()) {
            customer = erp.getDoc("Customer", asString(so.get("customer")));
        }
        Map<String, Map<String, Object>> records = headerRecords(so, customer, addr);
        final String builtAddress = address;
        final String builtCity = city;
        final String builtPostalCode = addr != null ? asString(addr.get("pincode")) : null;
        final String builtWarehouse = firstNonBlank(asString(so.get("set_warehouse")), firstWarehouse);

        return ErpPendingOrderPreviewDTO.builder()
                .source("ERPNEXT")
                .erpOrderId(mappedString(ERP_ORDER_ID, records, () -> erpOrderId))
                .saleOrderRef(mappedString(SALE_ORDER_REF, records, () -> erpOrderId))
                // No delivery note exists until the order is delivered, so there is no number to
                // read; a tenant that has one elsewhere can map it.
                .blNumber(mappedString(BL_NUMBER, records, () -> null))
                .customerRef(mappedString(CUSTOMER_REF, records, () -> asString(so.get("po_no"))))
                .customerName(mappedString(CUSTOMER_NAME, records, () -> asString(so.get("customer_name"))))
                .customerPhone(mappedString(CUSTOMER_PHONE, records, () -> asString(so.get("contact_mobile"))))
                .deliveryAddress(mappedString(DELIVERY_ADDRESS, records, () -> builtAddress))
                .deliveryCity(mappedString(DELIVERY_CITY, records, () -> builtCity))
                .deliveryPostalCode(mappedString(DELIVERY_POSTAL_CODE, records, () -> builtPostalCode))
                .deliveryInstructions(mappedString(DELIVERY_INSTRUCTIONS, records, () -> asString(so.get("instructions"))))
                .totalAmount(mappedDecimal(TOTAL_AMOUNT, records, () -> asBigDecimal(so.get("grand_total"))))
                .currency(mappedString(CURRENCY, records, () -> asString(so.get("currency"))))
                // Default false: see CanonicalField.COD_REQUIRED.
                .codRequired(mappedBoolean(COD_REQUIRED, records, () -> false))
                .codAmount(mappedDecimal(COD_AMOUNT, records, () -> asBigDecimal(so.get("grand_total"))))
                .priority(mappedString(PRIORITY, records, () -> "NORMAL"))
                .scheduledAt(mappedDateTime(SCHEDULED_AT, records, () -> parseDateTime(so.get("delivery_date"), null)))
                .dateOrder(mappedDateTime(DATE_ORDER, records, () -> parseDateTime(so.get("transaction_date"), null)))
                .items(items)
                .totalQuantity(totalQty)
                .totalWeightKg(totalWeight)
                .warehouseCode(mappedString(WAREHOUSE_CODE, records, () -> builtWarehouse))
                .warehouseName(mappedString(WAREHOUSE_NAME, records, () -> builtWarehouse))
                .ready(mappedBoolean(READY, records, () -> true))
                // ERP values ASM has no field of its own for.
                .customFields(emptyToNull(fieldMapping.resolveCustomFields(records)))
                .build();
    }

    // ── Warehouses (source depots) ───────────────────────────────────────────────

    @Override
    public List<ErpWarehouseDTO> getWarehouses() {
        long start = System.currentTimeMillis();
        String company = resolveCompany();
        if (company == null) return List.of();

        List<List<Object>> filters = List.of(
                List.of("is_group", "=", 0),          // skip parent folders ("All Warehouses")
                List.of("disabled", "=", 0),
                companyFilter(company));

        List<Map<String, Object>> rows = erp.getList("Warehouse",
                List.of("name", "warehouse_name", "warehouse_type"), filters, 0, "name asc");

        List<ErpWarehouseDTO> result = new ArrayList<>();
        for (Map<String, Object> w : rows) {
            // Drop logical transit warehouses (Goods In Transit) — not physical dispatch depots.
            // Filtered in Java, not in the query: a SQL "warehouse_type != 'Transit'" would also exclude
            // the physical warehouses whose type is NULL. (WIP has a NULL type too → left for the admin
            // to uncheck at the Bind step; only Transit is auto-excluded here.)
            if ("Transit".equalsIgnoreCase(asString(w.get("warehouse_type")))) continue;
            String code = asString(w.get("name"));   // the warehouse name IS the stable key ASM maps to a depot
            if (code == null) continue;
            // ERPNext warehouses carry no coordinates → ASM geocodes / the admin sets GPS at bind time.
            result.add(ErpWarehouseDTO.builder()
                    .erpWarehouseId(code)
                    .code(code)
                    .name(firstNonBlank(asString(w.get("warehouse_name")), code))
                    .latitude(null)
                    .longitude(null)
                    .build());
        }
        log.info("[erpnext] getWarehouses company='{}' count={} durationMs={}", company, result.size(), System.currentTimeMillis() - start);
        return result;
    }

