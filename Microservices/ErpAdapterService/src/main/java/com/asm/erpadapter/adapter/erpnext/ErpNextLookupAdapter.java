    // ── Company (tenant's own selling entity) ────────────────────────────────────

    @Override
    public ErpCompanyDTO getCompany() {
        String company = resolveCompany();
        if (company == null) return null;
        Map<String, Object> c = erp.getDoc("Company", company);
        if (c == null) return null;

        // Company address is a linked Address doc (no inline street/city); best-effort resolve.
        String address = null;
        String city = null;
        Map<String, Object> addr = firstCompanyAddress(company);
        if (addr != null) {
            address = buildAddress(addr);
            city = asString(addr.get("city"));
        }

        return ErpCompanyDTO.builder()
                .name(firstNonBlank(asString(c.get("company_name")), company))
                .address(address)
                .city(city)
                .phone(asString(c.get("phone_no")))
                .email(asString(c.get("email")))
                .vat(asString(c.get("tax_id")))
                .website(asString(c.get("website")))
                .logo(asString(c.get("company_logo")))
                .build();
    }

    /** Fetch the company's primary Address via the Dynamic Link on the Address doctype (best-effort). */
    private Map<String, Object> firstCompanyAddress(String company) {
        // Address links to its owner through the child table "Dynamic Link"; filter by link_name.
        List<Map<String, Object>> rows = erp.getList("Address",
                List.of("name"),
                List.of(List.of("link_name", "=", company)),
                1, "creation asc");
        if (rows.isEmpty()) return null;
        return erp.getDoc("Address", asString(rows.get(0).get("name")));
    }

    /** One batch fetch of the Sales Orders' shipping addresses → address name → [address, city]. */
    private Map<String, Map<String, Object>> batchAddresses(List<Map<String, Object>> soRows) {
        List<Object> names = new ArrayList<>();
        for (Map<String, Object> r : soRows) {
            String n = firstNonBlank(asString(r.get("shipping_address_name")), asString(r.get("customer_address")));
            if (n != null && !names.contains(n)) names.add(n);
        }
        if (names.isEmpty()) return Map.of();
        List<Map<String, Object>> addrs = listWidened("Address",
                List.of("name", "address_line1", "address_line2", "city", "pincode"),
                List.of(List.of("name", "in", names)), 0, null);
        Map<String, Map<String, Object>> byName = new HashMap<>();
        for (Map<String, Object> a : addrs) {
            String n = asString(a.get("name"));
            if (n != null) byName.put(n, a);
        }
        return byName;
    }

    /**
     * The adapter's own field list plus whatever this tenant mapped onto {@code doctype}.
     *
     * <p>Without this a mapping points at a field the request never asked for, so the value is
     * absent from the row and resolves to nothing — and the integrator cannot tell "my ERP field is
     * empty" from "the system never fetched it". Only needed on the list reads; {@code getDoc}
     * already returns the whole document.
     */
    private List<String> widened(List<String> base, String doctype) {
        java.util.LinkedHashSet<String> all = new java.util.LinkedHashSet<>(base);
        all.addAll(fieldMapping.extraFieldsFor(doctype));
        return List.copyOf(all);
    }

    /**
     * List {@code doctype} asking for the mapped fields too, falling back to the base list if that is
     * refused.
     *
     * <p>Frappe rejects the <em>whole query</em> when one requested field does not exist — so a single
     * bad path would empty the pending-orders screen rather than blank one value, and the screen would
     * say the ERP has no orders. The retry keeps that failure proportionate: the mapping stops
     * resolving in the list, the orders still arrive.
     */
    private List<Map<String, Object>> listWidened(String doctype, List<String> base,
                                                  List<List<Object>> filters, int limit, String orderBy) {
        List<String> fields = widened(base, doctype);
        if (fields.size() == base.size()) return erp.getList(doctype, base, filters, limit, orderBy);
        try {
            return erp.getListStrict(doctype, fields, filters, limit, orderBy);
        } catch (Exception e) {
            log.warn("[erpnext] {} list refused the mapped fields, retrying without them: {}",
                    doctype, e.getMessage());
            return erp.getList(doctype, base, filters, limit, orderBy);
        }
    }

    /**
     * The customer documents these orders point at, in one call — and only when the tenant has
     * actually mapped something onto Customer.
     *
     * <p>Mirrors {@link #batchAddresses}. Without it a Customer-scoped mapping resolved on the
     * preview and came back blank in the list, so the same order showed two different values
     * depending on which screen you were looking at.
     */
    private Map<String, Map<String, Object>> batchCustomers(List<Map<String, Object>> soRows) {
        if (fieldMapping.extraFieldsFor("Customer").isEmpty()) return Map.of();
        List<Object> names = new ArrayList<>();
        for (Map<String, Object> r : soRows) {
            String n = asString(r.get("customer"));
            if (n != null && !names.contains(n)) names.add(n);
        }
        if (names.isEmpty()) return Map.of();
        Map<String, Map<String, Object>> byName = new HashMap<>();
        for (Map<String, Object> c : listWidened("Customer", List.of("name", "customer_name"),
                List.of(List.of("name", "in", names)), 0, null)) {
            String n = asString(c.get("name"));
            if (n != null) byName.put(n, c);
        }
        return byName;
    }

    /** Resolve the customer's shipping (or primary) Address name via the Dynamic Link (best-effort). */
    private String defaultCustomerAddress(String customer) {
        if (customer == null) return null;
        List<Map<String, Object>> rows = erp.getList("Address",
                List.of("name", "is_shipping_address"),
                List.of(List.of("link_name", "=", customer)),
                10, "is_shipping_address desc");
        if (rows.isEmpty()) return null;
        for (Map<String, Object> r : rows) if (asBool(r.get("is_shipping_address"))) return asString(r.get("name"));
        return asString(rows.get(0).get("name"));
    }

